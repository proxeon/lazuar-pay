import { ApiKeyAuthenticationProvider, ApiKeyLocation } from "@microsoft/kiota-abstractions";
import { FetchRequestAdapter } from "@microsoft/kiota-http-fetchlibrary";
import { createLhdnClient } from "./generated/lhdnClient.js";

// Export everything from the generated models so consumers can use the types
export * from "./generated/models/index.js";

export interface LhdnClientOptions {
  apiKey: string;
  baseUrl?: string;
}

/**
 * Initializes the Lazuar LHDN API Client.
 */
export function initLhdnClient(options: LhdnClientOptions) {
  // 1. Setup the API Key Authentication Provider.
  // Always send Authorization: Bearer sk_* so raw keys and pre-prefixed values both work.
  const authorizationValue = options.apiKey.startsWith("Bearer ")
    ? options.apiKey
    : `Bearer ${options.apiKey}`;
  const authProvider = new ApiKeyAuthenticationProvider(
    authorizationValue,
    "Authorization",
    ApiKeyLocation.Header
  );

  // 2. Initialize the standard Fetch Request Adapter (natively includes exponential backoff retries)
  const adapter = new FetchRequestAdapter(authProvider);
  
  if (options.baseUrl) {
    adapter.baseUrl = options.baseUrl;
  }

  // 3. Return the functional client generated by Kiota v2
  return createLhdnClient(adapter);
}
